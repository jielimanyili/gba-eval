def gba_header(title: str = "GBAEVAL") -> bytes:
    """Build a valid 192-byte GBA cartridge header (program follows at 0xC0)."""
    h = bytearray(0xC0)
    # 0x00: ARM branch to the code start (0x080000C0).
    struct.pack_into("<I", h, 0x00, 0xEA00_002E)  # B 0x080000C0
    # 0x04: Nintendo logo (156 bytes).
    assert len(NINTENDO_LOGO) == 156
    h[0x04:0xA0] = NINTENDO_LOGO
    # 0xA0: game title (12 bytes).
    h[0xA0:0xAC] = title.ljust(12).encode("ascii")
    # 0xAC: game code (4), 0xB0: maker code (2), 0xB2: fixed 0x96.
    h[0xAC:0xB0] = b"GBEV"
    h[0xB0:0xB2] = b"01"
    h[0xB2] = 0x96
    # 0xB3..0xBC stay zero (unit code, device type, reserved, version).
    # 0xBD: complement check — sum over 0xA0..0xBC + 0x19 must be 0 mod 256.
    h[0xBD] = (-(0x19 + sum(h[0xA0:0xBD]))) & 0xFF
    return bytes(h)


def fill(color_instr: int) -> bytes:
    words = [
        0xE3A0_3404,  # MOV r3, #0x04000000
        0xE3A0_4003,  # MOV r4, #3
        0xE1C3_40B0,  # STRH r4, [r3]
        0xE3A0_0406,  # MOV r0, #0x06000000
        0xE3A0_1C96,  # MOV r1, #0x9600
        color_instr,  # MOV r2, #color
        0xE0C0_20B2,  # STRH r2, [r0], #2
        0xE251_1001,  # SUBS r1, r1, #1
        0x1AFF_FFFC,  # BNE loop
        0xEAFF_FFFE,  # B .
    ]
    return gba_header("GBAEVAL") + b"".join(struct.pack("<I", w) for w in words)


ROMS = {
    "fill_red.gba": fill(0xE3A0_201F),   # MOV r2, #0x001F
    "fill_blue.gba": fill(0xE3A0_2B1F),  # MOV r2, #0x7C00 (imm8 0x1F, ROR 22)
}


def main() -> None:
    out_dir = os.path.dirname(os.path.abspath(__file__))
    for name, data in ROMS.items():
        path = os.path.join(out_dir, name)
        with open(path, "wb") as f:
            f.write(data)
        print(f"wrote {path} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
